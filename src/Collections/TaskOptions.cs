namespace Collections;

/// <summary>
/// Task options available
/// </summary>
public enum TaskOptions
{
    /// <summary>
    /// Represent an option to perform list operations.
    /// </summary>
    List = 1,

    /// <summary>
    /// Represent an option to perform stack operations.
    /// </summary>
    Stack = 2,

    /// <summary>
    /// Represent an option to perform queue operations.
    /// </summary>
    Queue = 3,

    /// <summary>
    /// Represent an option to perform dictionary operations.
    /// </summary>
    Dictionary = 4,

    /// <summary>
    /// Represents an option to exit the application.
    /// </summary>
    Exit = 5,
}
